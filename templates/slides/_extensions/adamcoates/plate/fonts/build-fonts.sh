#!/usr/bin/env bash
# Regenerate _inter.scss: subset the Inter woff2 files and inline them as data
# URIs.
#
# The fonts have to be *inside* the stylesheet. `deploy` only ships index.html,
# poll.html and index_files/, so anything referenced by a relative URL out of
# _extensions/ would 404 on the live site — and a lecture room with no wifi
# would fall back to a system font mid-talk.
#
# Subsetting keeps that affordable: Latin + Latin Extended-A + Greek (for α, σ,
# χ² in prose) + the punctuation, arrows and maths operators that actually turn
# up on slides. ~110 KB per weight becomes ~25 KB.
#
# Run from anywhere, inside the nix devShell (needs pyftsubset from fonttools):
#   ./_extensions/adamcoates/plate/fonts/build-fonts.sh
set -euo pipefail
cd "$(dirname "$0")"

UNICODES='U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0100-017F,U+0370-03FF,U+2000-206F,U+2070-209F,U+20A0-20BF,U+2122,U+2190-21FF,U+2200-22FF,U+2260,U+25A0-25CF,U+2713-2717,U+FB00-FB04'

# Light (300) carries the theme: headings, the cover title and table text are all
# set in it, and Light Italic does the accented subtitle and h3. Everything from
# 400 up is there for body copy and emphasis.
declare -A FACES=(
  [Inter-Light]="300 normal"
  [Inter-LightItalic]="300 italic"
  [Inter-Regular]="400 normal"
  [Inter-Italic]="400 italic"
  [Inter-Medium]="500 normal"
  [Inter-SemiBold]="600 normal"
  [Inter-Bold]="700 normal"
)

out=_inter.scss
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

{
  echo "// GENERATED by fonts/build-fonts.sh — do not edit by hand."
  echo "// Inter v4.1 by Rasmus Andersson, SIL Open Font License 1.1 (fonts/LICENSE.txt)."
  echo "// Subset to Latin/Latin-Ext/Greek/punctuation/arrows/maths and inlined as"
  echo "// data URIs so a deck needs no network and no files outside index.html."
  echo
} > "$out"

for face in "${!FACES[@]}"; do
  read -r weight style <<< "${FACES[$face]}"
  pyftsubset "$face.woff2" \
    --unicodes="$UNICODES" \
    --layout-features='kern,liga,clig,calt,tnum,frac,ccmp,locl,mark,mkmk' \
    --flavor=woff2 \
    --output-file="$tmp/$face.woff2"
  b64=$(base64 -w0 "$tmp/$face.woff2")
  printf 'Subset %-18s %6s bytes -> %7s bytes base64\n' \
    "$face" "$(stat -c%s "$face.woff2")" "${#b64}" >&2
  {
    echo "@font-face {"
    echo "  font-family: \"Inter\";"
    echo "  font-style: $style;"
    echo "  font-weight: $weight;"
    echo "  font-display: block;"
    echo "  src: url(data:font/woff2;charset=utf-8;base64,$b64) format(\"woff2\");"
    echo "}"
    echo
  } >> "$out"
done

echo "wrote $(pwd)/$out ($(stat -c%s "$out") bytes)" >&2
